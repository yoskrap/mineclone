import * as THREE from 'three';
import { World, CH } from '../js/world.js';
import { B, matchRecipe, breakTime, I } from '../js/blocks.js';
import { hashSeed } from '../js/noise.js';
globalThis.performance ??= { now: () => Date.now() };
const scene = new THREE.Scene();
const w = new World({ seed: hashSeed('test'), scene, materials: { opaque: new THREE.MeshBasicMaterial(), water: new THREE.MeshBasicMaterial() } });
const sp = w.findSpawn(); console.log('spawn', sp);
let t = performance.now();
for (let i = 0; i < 40; i++) w.update(sp.x, sp.z, 4, 1000);
console.log('chunks', w.chunks.size, 'meshed', w.meshCount(), 'ms', (performance.now() - t).toFixed(0), 'gen', w.stats.generated);
console.log('ready', w.readyAround(sp.x, sp.z, 2), 'surface', w.surfaceY(Math.floor(sp.x), Math.floor(sp.z)));
let tris = 0; for (const c of w.chunks.values()) if (c.mesh) tris += c.mesh.geometry.index.count / 3; console.log('tris', tris);
const counts = {}; for (const c of w.chunks.values()) for (const v of c.data) counts[v] = (counts[v] || 0) + 1; console.log(counts);
const sy = w.surfaceY(Math.floor(sp.x), Math.floor(sp.z));
console.log('ray down', w.raycast({ x: sp.x, y: sy + 2, z: sp.z }, new THREE.Vector3(0, -1, 0.0001).normalize(), 6));
console.log(w.setBlock(Math.floor(sp.x), sy - 1, Math.floor(sp.z), 0), Object.keys(w.diffs));
t = performance.now(); w.update(sp.x, sp.z, 4, 100); console.log('remesh ms', (performance.now() - t).toFixed(1));
console.log('recipes', matchRecipe([0, B.LOG, 0, 0], 2), matchRecipe([B.PLANKS,B.PLANKS,0,B.PLANKS,I.STICK,0,0,I.STICK,0],3), matchRecipe([0,B.PLANKS,B.PLANKS,0,I.STICK,B.PLANKS,0,I.STICK,0],3));
console.log('break', breakTime(B.STONE, 0), breakTime(B.STONE, I.WOODEN_PICKAXE), breakTime(B.DIRT, 0));
